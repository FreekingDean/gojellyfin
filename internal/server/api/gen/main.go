package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"log"
	"os"
	"sort"
	"strings"
)

const (
	src   = "jellyfinapi.gen.go"
	dst   = "unimplemented.gen.go"
	iface = "StrictServerInterface"

	specPath  = "../../../spec/jellyfin-openapi-10.10.0.json"
	publicDst = "public.gen.go"
)

var httpMethods = map[string]bool{
	"get": true, "put": true, "post": true, "delete": true,
	"options": true, "head": true, "patch": true, "trace": true,
}

func main() {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, src, nil, 0)
	if err != nil {
		log.Fatal(err)
	}

	writeUnimplemented(fset, f)
	writePublicOperations(f.Name.Name)
}

func writeUnimplemented(fset *token.FileSet, f *ast.File) {
	methods := findInterface(f, iface)
	if methods == nil {
		log.Fatalf("%s not found in %s", iface, src)
	}

	out := &bytes.Buffer{}
	fmt.Fprintf(out, `// Code generated by gen. DO NOT EDIT.

package %s

import (
	"context"
	"errors"
)

var ErrNotImplemented = errors.New("not implemented")

type Unimplemented struct{}
`, f.Name.Name)

	for _, m := range methods.List {
		fn, ok := m.Type.(*ast.FuncType)
		if !ok || len(m.Names) != 1 {
			continue
		}
		sig := strings.TrimPrefix(render(fset, fn), "func")
		fmt.Fprintf(out, "\nfunc (Unimplemented) %s%s {\n\treturn %s\n}\n", m.Names[0].Name, sig, returns(fn))
	}

	write(dst, out.Bytes())
}

func writePublicOperations(pkg string) {
	b, err := os.ReadFile(specPath)
	if err != nil {
		log.Fatal(err)
	}

	var doc struct {
		Paths map[string]map[string]json.RawMessage `json:"paths"`
	}
	if err := json.Unmarshal(b, &doc); err != nil {
		log.Fatal(err)
	}

	ids := make([]string, 0)
	for _, item := range doc.Paths {
		for method, raw := range item {
			if !httpMethods[strings.ToLower(method)] {
				continue
			}

			var op struct {
				OperationID string            `json:"operationId"`
				Security    []json.RawMessage `json:"security"`
			}
			if err := json.Unmarshal(raw, &op); err != nil {
				log.Fatal(err)
			}
			if op.OperationID != "" && len(op.Security) == 0 {
				ids = append(ids, op.OperationID)
			}
		}
	}
	sort.Strings(ids)

	out := &bytes.Buffer{}
	fmt.Fprintf(out, `// Code generated by gen. DO NOT EDIT.

package %s

var PublicOperations = map[string]bool{
`, pkg)

	for _, id := range ids {
		fmt.Fprintf(out, "\t%q: true,\n", id)
	}
	fmt.Fprint(out, "}\n")

	write(publicDst, out.Bytes())
}

func write(path string, b []byte) {
	formatted, err := format.Source(b)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(path, formatted, 0644); err != nil {
		log.Fatal(err)
	}
}

func findInterface(f *ast.File, name string) *ast.FieldList {
	for _, d := range f.Decls {
		gd, ok := d.(*ast.GenDecl)
		if !ok || gd.Tok != token.TYPE {
			continue
		}
		for _, s := range gd.Specs {
			ts := s.(*ast.TypeSpec)
			it, ok := ts.Type.(*ast.InterfaceType)
			if ok && ts.Name.Name == name {
				return it.Methods
			}
		}
	}
	return nil
}

func returns(fn *ast.FuncType) string {
	vals := make([]string, 0, len(fn.Results.List))
	for range fn.Results.List {
		vals = append(vals, "nil")
	}
	vals[len(vals)-1] = "ErrNotImplemented"
	return strings.Join(vals, ", ")
}

func render(fset *token.FileSet, n ast.Node) string {
	b := &bytes.Buffer{}
	if err := printer.Fprint(b, fset, n); err != nil {
		log.Fatal(err)
	}
	return b.String()
}
