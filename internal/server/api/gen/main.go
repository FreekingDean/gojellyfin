package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"log"
	"os"
	"sort"
	"strings"
)

const (
	src   = "jellyfinapi.gen.go"
	dst   = "unimplemented.gen.go"
	iface = "StrictServerInterface"

	specPath        = "../../../spec/jellyfin-openapi-stable.patched.json"
	versionSpecPath = "../../../spec/jellyfin-openapi-stable.json"
	publicDst       = "public.gen.go"
	policyDst       = "policies.gen.go"
	queryParamDst   = "queryparams.gen.go"

	versionDst = "../../system/jellyfinversion.gen.go"
	versionPkg = "system"
)

var httpMethods = map[string]bool{
	"get": true, "put": true, "post": true, "delete": true,
	"options": true, "head": true, "patch": true, "trace": true,
}

func main() {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, src, nil, 0)
	if err != nil {
		log.Fatal(err)
	}

	methods := findInterface(f, iface)
	if methods == nil {
		log.Fatalf("%s not found in %s", iface, src)
	}

	doc := readSpec()
	names := methodNames(methods)
	writeUnimplemented(fset, f, methods)
	emit(publicDst, f.Name.Name, block{"var PublicOperations = map[string]bool", publicOperations(doc, names)})
	emit(policyDst, f.Name.Name, block{"var OperationPolicies = map[string][]string", operationPolicies(doc, names)})
	writeQueryParameters(f.Name.Name, doc)
	writeJellyfinVersion()
}

func writeJellyfinVersion() {
	b, err := os.ReadFile(versionSpecPath)
	if err != nil {
		log.Fatal(err)
	}

	var doc struct {
		Info struct {
			Version string `json:"version"`
		} `json:"info"`
	}
	if err := json.Unmarshal(b, &doc); err != nil {
		log.Fatal(err)
	}
	if doc.Info.Version == "" {
		log.Fatalf("%s declares no info.version", versionSpecPath)
	}

	out := &bytes.Buffer{}
	fmt.Fprintf(out, `// Code generated by gen. DO NOT EDIT.

package %s

const JellyfinVersion = %q
`, versionPkg, doc.Info.Version)

	write(versionDst, out.Bytes())
}

type parameter struct {
	Name   string      `json:"name"`
	In     string      `json:"in"`
	Schema paramSchema `json:"schema"`
}

type operation struct {
	ID         string                `json:"operationId"`
	Security   []map[string][]string `json:"security"`
	Parameters []parameter           `json:"parameters"`
}

type spec struct {
	operations []operation
	schemas    map[string]paramSchema
}

func readSpec() spec {
	b, err := os.ReadFile(specPath)
	if err != nil {
		log.Fatal(err)
	}

	var doc struct {
		Paths      map[string]map[string]json.RawMessage `json:"paths"`
		Components struct {
			Schemas map[string]paramSchema `json:"schemas"`
		} `json:"components"`
	}
	if err := json.Unmarshal(b, &doc); err != nil {
		log.Fatal(err)
	}

	operations := []operation{}
	for _, item := range doc.Paths {
		for method, raw := range item {
			if !httpMethods[strings.ToLower(method)] {
				continue
			}

			var op operation
			if err := json.Unmarshal(raw, &op); err != nil {
				log.Fatal(err)
			}
			operations = append(operations, op)
		}
	}

	return spec{operations: operations, schemas: doc.Components.Schemas}
}

func methodNames(methods *ast.FieldList) map[string]string {
	names := make(map[string]string, methods.NumFields())
	for _, m := range methods.List {
		if len(m.Names) == 1 {
			names[normalize(m.Names[0].Name)] = m.Names[0].Name
		}
	}

	return names
}

func method(names map[string]string, op operation) string {
	name, ok := names[normalize(op.ID)]
	if !ok {
		log.Fatalf("no %s method for operation %s", iface, op.ID)
	}

	return name
}

func publicOperations(doc spec, names map[string]string) []string {
	lines := []string{}
	for _, op := range doc.operations {
		if op.ID != "" && len(op.Security) == 0 {
			lines = append(lines, fmt.Sprintf("%q: true,", method(names, op)))
		}
	}

	return lines
}

func operationPolicies(doc spec, names map[string]string) []string {
	secured := map[string]bool{}
	lines := []string{}
	for _, op := range doc.operations {
		if op.ID == "" {
			continue
		}

		name := method(names, op)
		secured[name] = true
		if len(op.Security) == 0 {
			continue
		}

		scopes := []string{}
		for _, scheme := range op.Security {
			for _, granted := range scheme {
				scopes = append(scopes, granted...)
			}
		}
		sort.Strings(scopes)
		quoted := make([]string, 0, len(scopes))
		for _, scope := range scopes {
			quoted = append(quoted, fmt.Sprintf("%q", scope))
		}
		lines = append(lines, fmt.Sprintf("%q: {%s},", name, strings.Join(quoted, ", ")))
	}

	for _, name := range names {
		if !secured[name] {
			log.Fatalf("%s has no operation in the spec: %s", iface, name)
		}
	}

	return lines
}

type block struct {
	declaration string
	lines       []string
}

func emit(path, pkg string, blocks ...block) {
	out := &bytes.Buffer{}
	fmt.Fprintf(out, "// Code generated by gen. DO NOT EDIT.\n\npackage %s\n", pkg)
	for _, b := range blocks {
		sort.Strings(b.lines)
		fmt.Fprintf(out, "\n%s{\n", b.declaration)
		for _, line := range b.lines {
			fmt.Fprintf(out, "\t%s\n", line)
		}
		fmt.Fprint(out, "}\n")
	}

	write(path, out.Bytes())
}

func writeUnimplemented(fset *token.FileSet, f *ast.File, methods *ast.FieldList) {
	out := &bytes.Buffer{}
	fmt.Fprintf(out, `// Code generated by gen. DO NOT EDIT.

package %s

import (
	"context"
	"errors"
)

var ErrNotImplemented = errors.New("not implemented")

type Unimplemented struct{}
`, f.Name.Name)

	for _, m := range methods.List {
		fn, ok := m.Type.(*ast.FuncType)
		if !ok || len(m.Names) != 1 {
			continue
		}
		sig := strings.TrimPrefix(render(fset, fn), "func")
		fmt.Fprintf(out, "\nfunc (Unimplemented) %s%s {\n\treturn %s\n}\n", m.Names[0].Name, sig, returns(fn))
	}

	write(dst, out.Bytes())
}

type paramSchema struct {
	Type   string        `json:"type"`
	Format string        `json:"format"`
	Ref    string        `json:"$ref"`
	Enum   []any         `json:"enum"`
	AllOf  []paramSchema `json:"allOf"`
	Items  *paramSchema  `json:"items"`
}

func (s paramSchema) commaFree(schemas map[string]paramSchema) bool {
	if s.Ref != "" {
		return schemas[strings.TrimPrefix(s.Ref, "#/components/schemas/")].commaFree(schemas)
	}
	if len(s.AllOf) == 1 {
		return s.AllOf[0].commaFree(schemas)
	}
	return len(s.Enum) > 0 || s.Format == "uuid" || s.Type == "integer" || s.Type == "number" || s.Type == "boolean"
}

func writeQueryParameters(pkg string, doc spec) {
	canonical := map[string]string{}
	arrays := map[string]bool{}
	commaFree := map[string]bool{}
	for _, op := range doc.operations {
		for _, parameter := range op.Parameters {
			if parameter.In != "query" {
				continue
			}

			key := strings.ToLower(parameter.Name)
			if existing, ok := canonical[key]; ok && existing != parameter.Name {
				log.Fatalf("query parameter %q collides with %q", parameter.Name, existing)
			}
			canonical[key] = parameter.Name

			array := parameter.Schema.Type == "array" && parameter.Schema.Items != nil
			if previous, ok := arrays[parameter.Name]; ok {
				array = array && previous
			}
			arrays[parameter.Name] = array
			if array && parameter.Schema.Items.commaFree(doc.schemas) {
				commaFree[parameter.Name] = true
			}
		}
	}

	parameters := []string{}
	delimited := []string{}
	for key, name := range canonical {
		parameters = append(parameters, fmt.Sprintf("%q: %q,", key, name))
		if arrays[name] && commaFree[name] {
			delimited = append(delimited, fmt.Sprintf("%q: true,", name))
		}
	}

	emit(queryParamDst, pkg,
		block{"var QueryParameters = map[string]string", parameters},
		block{"var CommaDelimitedQueryParameters = map[string]bool", delimited},
	)
}

func normalize(s string) string {
	return strings.ToLower(strings.ReplaceAll(s, "_", ""))
}

func write(path string, b []byte) {
	formatted, err := format.Source(b)
	if err != nil {
		_ = os.WriteFile(path+".broken", b, 0644)
		log.Fatalf("%s: %v (unformatted output written to %s.broken)", path, err, path)
	}
	if err := os.WriteFile(path, formatted, 0644); err != nil {
		log.Fatal(err)
	}
}

func findInterface(f *ast.File, name string) *ast.FieldList {
	for _, d := range f.Decls {
		gd, ok := d.(*ast.GenDecl)
		if !ok || gd.Tok != token.TYPE {
			continue
		}
		for _, s := range gd.Specs {
			ts := s.(*ast.TypeSpec)
			it, ok := ts.Type.(*ast.InterfaceType)
			if ok && ts.Name.Name == name {
				return it.Methods
			}
		}
	}
	return nil
}

func returns(fn *ast.FuncType) string {
	vals := make([]string, 0, len(fn.Results.List))
	for range fn.Results.List {
		vals = append(vals, "nil")
	}
	vals[len(vals)-1] = "ErrNotImplemented"
	return strings.Join(vals, ", ")
}

func render(fset *token.FileSet, n ast.Node) string {
	b := &bytes.Buffer{}
	if err := printer.Fprint(b, fset, n); err != nil {
		log.Fatal(err)
	}
	return b.String()
}
