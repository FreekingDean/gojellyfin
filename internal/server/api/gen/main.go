package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"log"
	"os"
	"sort"
	"strings"
)

const (
	src   = "jellyfinapi.gen.go"
	dst   = "unimplemented.gen.go"
	iface = "StrictServerInterface"

	specPath      = "../../../spec/jellyfin-openapi-10.10.0.json"
	publicDst     = "public.gen.go"
	queryParamDst = "queryparams.gen.go"
)

var httpMethods = map[string]bool{
	"get": true, "put": true, "post": true, "delete": true,
	"options": true, "head": true, "patch": true, "trace": true,
}

func main() {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, src, nil, 0)
	if err != nil {
		log.Fatal(err)
	}

	methods := findInterface(f, iface)
	if methods == nil {
		log.Fatalf("%s not found in %s", iface, src)
	}

	writeUnimplemented(fset, f, methods)
	writePublicOperations(f.Name.Name, methods)
	writeQueryParameters(f.Name.Name)
}

func writeUnimplemented(fset *token.FileSet, f *ast.File, methods *ast.FieldList) {
	out := &bytes.Buffer{}
	fmt.Fprintf(out, `// Code generated by gen. DO NOT EDIT.

package %s

import (
	"context"
	"errors"
)

var ErrNotImplemented = errors.New("not implemented")

type Unimplemented struct{}
`, f.Name.Name)

	for _, m := range methods.List {
		fn, ok := m.Type.(*ast.FuncType)
		if !ok || len(m.Names) != 1 {
			continue
		}
		sig := strings.TrimPrefix(render(fset, fn), "func")
		fmt.Fprintf(out, "\nfunc (Unimplemented) %s%s {\n\treturn %s\n}\n", m.Names[0].Name, sig, returns(fn))
	}

	write(dst, out.Bytes())
}

// oapi-codegen normalizes operation ids into Go method names, so the spec's
// GetBrandingCss_2 becomes GetBrandingCss2. The middleware only ever sees the
// normalized form.
func writePublicOperations(pkg string, methods *ast.FieldList) {
	methodNames := make(map[string]string, methods.NumFields())
	for _, m := range methods.List {
		if len(m.Names) == 1 {
			methodNames[normalize(m.Names[0].Name)] = m.Names[0].Name
		}
	}

	b, err := os.ReadFile(specPath)
	if err != nil {
		log.Fatal(err)
	}

	var doc struct {
		Paths map[string]map[string]json.RawMessage `json:"paths"`
	}
	if err := json.Unmarshal(b, &doc); err != nil {
		log.Fatal(err)
	}

	ids := make([]string, 0)
	for _, item := range doc.Paths {
		for method, raw := range item {
			if !httpMethods[strings.ToLower(method)] {
				continue
			}

			var op struct {
				OperationID string            `json:"operationId"`
				Security    []json.RawMessage `json:"security"`
			}
			if err := json.Unmarshal(raw, &op); err != nil {
				log.Fatal(err)
			}
			if op.OperationID == "" || len(op.Security) != 0 {
				continue
			}

			name, ok := methodNames[normalize(op.OperationID)]
			if !ok {
				log.Fatalf("no %s method for operation %s", iface, op.OperationID)
			}
			ids = append(ids, name)
		}
	}
	sort.Strings(ids)

	out := &bytes.Buffer{}
	fmt.Fprintf(out, `// Code generated by gen. DO NOT EDIT.

package %s

var PublicOperations = map[string]bool{
`, pkg)

	for _, id := range ids {
		fmt.Fprintf(out, "\t%q: true,\n", id)
	}
	fmt.Fprint(out, "}\n")

	write(publicDst, out.Bytes())
}

// Jellyfin clients send query parameters in PascalCase while the spec declares
// them camelCase, and the generated binding is case sensitive. This maps a
// lowercased name back to the spelling the binding expects.
func writeQueryParameters(pkg string) {
	b, err := os.ReadFile(specPath)
	if err != nil {
		log.Fatal(err)
	}

	var doc struct {
		Paths map[string]map[string]json.RawMessage `json:"paths"`
	}
	if err := json.Unmarshal(b, &doc); err != nil {
		log.Fatal(err)
	}

	canonical := map[string]string{}
	for _, item := range doc.Paths {
		for method, raw := range item {
			if !httpMethods[strings.ToLower(method)] {
				continue
			}

			var op struct {
				Parameters []struct {
					Name string `json:"name"`
					In   string `json:"in"`
				} `json:"parameters"`
			}
			if err := json.Unmarshal(raw, &op); err != nil {
				log.Fatal(err)
			}
			for _, parameter := range op.Parameters {
				if parameter.In != "query" {
					continue
				}

				key := strings.ToLower(parameter.Name)
				if existing, ok := canonical[key]; ok && existing != parameter.Name {
					log.Fatalf("query parameter %q collides with %q", parameter.Name, existing)
				}
				canonical[key] = parameter.Name
			}
		}
	}

	keys := make([]string, 0, len(canonical))
	for key := range canonical {
		keys = append(keys, key)
	}
	sort.Strings(keys)

	out := &bytes.Buffer{}
	fmt.Fprintf(out, `// Code generated by gen. DO NOT EDIT.

package %s

var QueryParameters = map[string]string{
`, pkg)

	for _, key := range keys {
		fmt.Fprintf(out, "\t%q: %q,\n", key, canonical[key])
	}
	fmt.Fprint(out, "}\n")

	write(queryParamDst, out.Bytes())
}

func normalize(s string) string {
	return strings.ToLower(strings.ReplaceAll(s, "_", ""))
}

func write(path string, b []byte) {
	formatted, err := format.Source(b)
	if err != nil {
		_ = os.WriteFile(path+".broken", b, 0644)
		log.Fatalf("%s: %v (unformatted output written to %s.broken)", path, err, path)
	}
	if err := os.WriteFile(path, formatted, 0644); err != nil {
		log.Fatal(err)
	}
}

func findInterface(f *ast.File, name string) *ast.FieldList {
	for _, d := range f.Decls {
		gd, ok := d.(*ast.GenDecl)
		if !ok || gd.Tok != token.TYPE {
			continue
		}
		for _, s := range gd.Specs {
			ts := s.(*ast.TypeSpec)
			it, ok := ts.Type.(*ast.InterfaceType)
			if ok && ts.Name.Name == name {
				return it.Methods
			}
		}
	}
	return nil
}

func returns(fn *ast.FuncType) string {
	vals := make([]string, 0, len(fn.Results.List))
	for range fn.Results.List {
		vals = append(vals, "nil")
	}
	vals[len(vals)-1] = "ErrNotImplemented"
	return strings.Join(vals, ", ")
}

func render(fset *token.FileSet, n ast.Node) string {
	b := &bytes.Buffer{}
	if err := printer.Fprint(b, fset, n); err != nil {
		log.Fatal(err)
	}
	return b.String()
}
